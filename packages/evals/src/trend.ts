/**
 * Trend renderer (ADR-12): history.jsonl → markdown table, newest last, one
 * row per recorded eval run, with deltas against the previous run of the
 * same mode — the "chart instead of an impression" 02 §10.2 asks for.
 *
 *   pnpm trend                 # print to stdout
 *   pnpm trend -- --out docs/evals/trend.md
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

// Repo root, not the CWD — `pnpm --filter` runs scripts with CWD at the
// package dir, so a relative --out/--history is anchored here to mean the
// same path regardless of where the script was invoked from.
const REPO_ROOT = fileURLToPath(new URL("../../../", import.meta.url));

const recordSchema = z.object({
  version: z.string(),
  timestamp: z.string(),
  mode: z.enum(["scripted", "live", "replay"]),
  aggregate: z.object({
    tasksTotal: z.number(),
    tasksPassed: z.number(),
    passRate: z.number(),
    retries: z.number(),
    escalations: z.number(),
    totalCostUsd: z.number(),
    avgCostPerTaskUsd: z.number(),
    totalTurns: z.number(),
  }),
});

type TrendRecord = z.infer<typeof recordSchema>;

function argValue(flag: string): string | undefined {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function delta(current: number, previous: number | undefined, digits = 1): string {
  if (previous === undefined) return "";
  const d = current - previous;
  if (d === 0) return " (=)";
  return ` (${d > 0 ? "+" : ""}${d.toFixed(digits)})`;
}

export function renderTrend(records: TrendRecord[]): string {
  const lines = [
    "# Eval suite trend (ADR-12)",
    "",
    "Generated by `pnpm --filter @mullion/evals trend` from `docs/evals/history.jsonl`.",
    "Deltas compare against the previous run of the same mode.",
    "",
    "| version | date | mode | pass | retries | escalations | cost (USD) | turns |",
    "|---|---|---|---|---|---|---|---|",
  ];
  const lastByMode = new Map<string, TrendRecord>();
  for (const r of records) {
    const prev = lastByMode.get(r.mode)?.aggregate;
    const a = r.aggregate;
    lines.push(
      `| ${r.version} | ${r.timestamp.slice(0, 10)} | ${r.mode} ` +
        `| ${a.tasksPassed}/${a.tasksTotal} (${(a.passRate * 100).toFixed(1)}%${delta(a.passRate * 100, prev ? prev.passRate * 100 : undefined)}) ` +
        `| ${a.retries}${delta(a.retries, prev?.retries, 0)} ` +
        `| ${a.escalations}${delta(a.escalations, prev?.escalations, 0)} ` +
        `| ${a.totalCostUsd.toFixed(4)}${delta(a.totalCostUsd, prev?.totalCostUsd, 4)} ` +
        `| ${a.totalTurns}${delta(a.totalTurns, prev?.totalTurns, 0)} |`,
    );
    lastByMode.set(r.mode, r);
  }
  if (records.length === 0) {
    lines.push("| _no recorded runs yet_ | | | | | | | |");
  }
  return `${lines.join("\n")}\n`;
}

export function parseHistory(raw: string): TrendRecord[] {
  return raw
    .split("\n")
    .filter((line) => line.trim().length > 0)
    .map((line) => recordSchema.parse(JSON.parse(line)));
}

/** Anchor a relative path to the repo root; leave an absolute one as-is. */
function anchor(path: string): string {
  return isAbsolute(path) ? path : resolve(REPO_ROOT, path);
}

async function main(): Promise<void> {
  const historyArg = argValue("--history");
  const historyPath = historyArg ? anchor(historyArg) : resolve(REPO_ROOT, "docs/evals/history.jsonl");
  let raw = "";
  try {
    raw = await readFile(historyPath, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  const markdown = renderTrend(parseHistory(raw));
  const out = argValue("--out");
  if (out) {
    const outPath = anchor(out);
    // The dir may not exist on a fresh checkout — create it, don't ENOENT.
    await mkdir(dirname(outPath), { recursive: true });
    await writeFile(outPath, markdown, "utf8");
    console.log(`wrote ${outPath}`);
  } else {
    console.log(markdown);
  }
}

// Renderer is imported by tests; only act as a CLI when invoked directly.
if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
